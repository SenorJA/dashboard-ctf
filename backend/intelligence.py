"""
intelligence.py -- MIRV Module

Continuous Intelligence — Periodic monitoring, change detection, and alerting
for watched targets (URLs, hosts, DNS records, HTTP headers, certificates,
technologies).

Inspired by PentesterFlow's continuous intelligence features, this module
provides:

  1. **Watch Definitions** — operators define what to monitor.
  2. **Snapshots** — captures the current state of a watched target.
  3. **Diff Detection** — compares new snapshot vs previous.
  4. **Alerts** — generates alerts when significant changes occur.
  5. **History** — stores snapshot history for trend analysis.

All functions are synchronous and thread-safe (module-level lock).
Stdlib only for core logic; collectors use ``urllib.request`` / ``ssl`` /
``socket`` with graceful fallback to synthetic data on failure.
"""

from __future__ import annotations

import hashlib
import json
import logging
import socket
import ssl
import threading
import uuid
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from typing import Any, Optional

# -- Logger (no secrets) --
_logger = logging.getLogger("vulnforge.intelligence")


# ════════════════════════════════════════════════════════════════
#  Constants
# ════════════════════════════════════════════════════════════════

VALID_WATCH_TYPES = frozenset({
    "http_headers",
    "certificate",
    "dns",
    "port_scan",
    "tech_stack",
    "page_content",
})

MAX_WATCHES = 1000
MAX_SNAPSHOTS_PER_WATCH = 100
MAX_ALERTS = 500
COLLECT_TIMEOUT = 10  # seconds for urllib / socket ops

SECURITY_HEADERS = frozenset({
    "strict-transport-security",
    "content-security-policy",
    "x-frame-options",
    "x-content-type-options",
    "x-xss-protection",
    "referrer-policy",
    "permissions-policy",
    "x-permitted-cross-domain-policies",
    "cross-origin-embedder-policy",
    "cross-origin-opener-policy",
    "cross-origin-resource-policy",
})


# ════════════════════════════════════════════════════════════════
#  Data classes
# ════════════════════════════════════════════════════════════════

@dataclass
class WatchDefinition:
    """A single watch / monitoring rule."""
    id: str
    name: str
    target: str                      # URL, IP, domain
    watch_type: str
    interval_seconds: int            # default 3600 (1 hour)
    enabled: bool = True
    created_at: str = ""
    last_check: Optional[str] = None
    tags: list[str] = field(default_factory=list)


@dataclass
class Snapshot:
    """A captured state of a watched target at a point in time."""
    id: str
    watch_id: str
    target: str
    watch_type: str
    captured_at: str
    data: dict                       # the actual snapshot payload
    previous_snapshot_id: Optional[str] = None


@dataclass
class DiffResult:
    """Outcome of comparing two snapshots."""
    watch_id: str
    target: str
    watch_type: str
    old_snapshot_id: Optional[str]
    new_snapshot_id: str
    changed: bool
    changes: list[dict]              # [{field, old_value, new_value, severity}]
    summary: str
    detected_at: str


@dataclass
class IntelAlert:
    """An alert generated by change detection."""
    id: str
    watch_id: str
    target: str
    alert_type: str                  # change_detected | target_down | cert_expiring | new_tech
    severity: str                    # info | low | medium | high | critical
    message: str
    details: dict
    created_at: str
    acknowledged: bool = False


# ════════════════════════════════════════════════════════════════
#  In-memory stores (thread-safe)
# ════════════════════════════════════════════════════════════════

_watches: dict[str, WatchDefinition] = {}
_snapshots: dict[str, list[Snapshot]] = {}     # watch_id -> [Snapshot, ...]
_alerts: dict[str, IntelAlert] = {}
_lock = threading.Lock()


# ════════════════════════════════════════════════════════════════
#  Helpers
# ════════════════════════════════════════════════════════════════

def _now_iso() -> str:
    """Return the current UTC time as an ISO-8601 string with 'Z' suffix."""
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%fZ")


def _severity_rank(sev: str) -> int:
    """Numeric rank for severity comparison (higher = more severe)."""
    return {"info": 0, "low": 1, "medium": 2, "high": 3, "critical": 4}.get(sev, 0)


def _max_severity(changes: list[dict]) -> str:
    """Return the highest severity among a list of change dicts."""
    if not changes:
        return "info"
    ranks = [_severity_rank(c.get("severity", "info")) for c in changes]
    max_rank = max(ranks) if ranks else 0
    for name, rank in {"info": 0, "low": 1, "medium": 2, "high": 3, "critical": 4}.items():
        if rank == max_rank:
            return name
    return "info"


# ════════════════════════════════════════════════════════════════
#  Watch CRUD
# ════════════════════════════════════════════════════════════════

def create_watch(
    name: str,
    target: str,
    watch_type: str,
    interval_seconds: int = 3600,
    tags: Optional[list[str]] = None,
) -> WatchDefinition:
    """Create and store a new watch definition.

    Raises ``ValueError`` if *watch_type* is invalid or the watch limit is
    reached.
    """
    if watch_type not in VALID_WATCH_TYPES:
        raise ValueError(f"Invalid watch_type '{watch_type}'. Must be one of {sorted(VALID_WATCH_TYPES)}")
    if not target or not target.strip():
        raise ValueError("target must be a non-empty string")

    with _lock:
        if len(_watches) >= MAX_WATCHES:
            raise ValueError(f"Watch limit reached ({MAX_WATCHES}). Delete existing watches first.")

        watch = WatchDefinition(
            id=str(uuid.uuid4()),
            name=name,
            target=target.strip(),
            watch_type=watch_type,
            interval_seconds=max(60, interval_seconds),
            enabled=True,
            created_at=_now_iso(),
            tags=list(tags) if tags else [],
        )
        _watches[watch.id] = watch
        _logger.info("Watch created: %s (%s)", watch.id, watch.watch_type)
        return watch


def get_watch(watch_id: str) -> Optional[WatchDefinition]:
    """Return a watch by ID, or ``None`` if not found."""
    return _watches.get(watch_id)


def list_watches(enabled_only: bool = False) -> list[WatchDefinition]:
    """Return all watches, optionally filtering to enabled-only."""
    with _lock:
        watches = list(_watches.values())
    if enabled_only:
        watches = [w for w in watches if w.enabled]
    return watches


def update_watch(watch_id: str, **kwargs) -> Optional[WatchDefinition]:
    """Update fields on an existing watch.  Returns the updated watch or
    ``None`` if not found.

    Allowed kwargs: name, target, watch_type, interval_seconds, enabled, tags.
    """
    with _lock:
        watch = _watches.get(watch_id)
        if watch is None:
            return None

        if "watch_type" in kwargs:
            wt = kwargs["watch_type"]
            if wt not in VALID_WATCH_TYPES:
                raise ValueError(f"Invalid watch_type '{wt}'")
            watch.watch_type = wt
        if "target" in kwargs:
            t = kwargs["target"]
            if not t or not str(t).strip():
                raise ValueError("target must be a non-empty string")
            watch.target = str(t).strip()
        if "name" in kwargs:
            watch.name = kwargs["name"]
        if "interval_seconds" in kwargs:
            watch.interval_seconds = max(60, int(kwargs["interval_seconds"]))
        if "enabled" in kwargs:
            watch.enabled = bool(kwargs["enabled"])
        if "tags" in kwargs:
            watch.tags = list(kwargs["tags"]) if kwargs["tags"] else []

        _logger.info("Watch updated: %s", watch_id)
        return watch


def delete_watch(watch_id: str) -> bool:
    """Delete a watch and its snapshot history.  Returns True on success."""
    with _lock:
        removed = _watches.pop(watch_id, None)
        if removed is not None:
            _snapshots.pop(watch_id, None)
            _logger.info("Watch deleted: %s", watch_id)
            return True
        return False


# ════════════════════════════════════════════════════════════════
#  Snapshot management
# ════════════════════════════════════════════════════════════════

def capture_snapshot(watch: WatchDefinition, data: dict) -> Snapshot:
    """Store a new snapshot for *watch* and return it.

    The previous snapshot ID is linked automatically.  Old snapshots are
    trimmed to ``MAX_SNAPSHOTS_PER_WATCH``.
    """
    now = _now_iso()
    with _lock:
        history = _snapshots.get(watch.id, [])
        prev_id = history[-1].id if history else None

        snap = Snapshot(
            id=str(uuid.uuid4()),
            watch_id=watch.id,
            target=watch.target,
            watch_type=watch.watch_type,
            captured_at=now,
            data=data,
            previous_snapshot_id=prev_id,
        )

        history.append(snap)
        # Trim oldest if over limit
        if len(history) > MAX_SNAPSHOTS_PER_WATCH:
            history = history[-MAX_SNAPSHOTS_PER_WATCH:]
        _snapshots[watch.id] = history

        # Update watch last_check
        if watch.id in _watches:
            _watches[watch.id].last_check = now

        _logger.info("Snapshot captured for watch %s", watch.id)
        return snap


def get_latest_snapshot(watch_id: str) -> Optional[Snapshot]:
    """Return the most recent snapshot for *watch_id*, or ``None``."""
    with _lock:
        history = _snapshots.get(watch_id, [])
    return history[-1] if history else None


def get_snapshot_history(watch_id: str, limit: int = 50) -> list[Snapshot]:
    """Return up to *limit* most recent snapshots (newest last)."""
    with _lock:
        history = list(_snapshots.get(watch_id, []))
    return history[-limit:]


# ════════════════════════════════════════════════════════════════
#  Diff engine
# ════════════════════════════════════════════════════════════════

def compute_diff(old_snapshot: Optional[Snapshot], new_snapshot: Snapshot) -> DiffResult:
    """Compare *old_snapshot* with *new_snapshot* and return a DiffResult.

    If *old_snapshot* is ``None``, the new snapshot is treated as a baseline
    (no changes detected).
    """
    now = _now_iso()

    if old_snapshot is None:
        return DiffResult(
            watch_id=new_snapshot.watch_id,
            target=new_snapshot.target,
            watch_type=new_snapshot.watch_type,
            old_snapshot_id=None,
            new_snapshot_id=new_snapshot.id,
            changed=False,
            changes=[],
            summary="Baseline snapshot captured — no previous data to compare.",
            detected_at=now,
        )

    # Dispatch to type-specific diff
    wt = new_snapshot.watch_type
    if wt == "http_headers":
        changes = _diff_http_headers(old_snapshot.data, new_snapshot.data)
    elif wt == "certificate":
        changes = _diff_certificate(old_snapshot.data, new_snapshot.data)
    elif wt == "dns":
        changes = _diff_dns(old_snapshot.data, new_snapshot.data)
    elif wt == "tech_stack":
        changes = _diff_tech_stack(old_snapshot.data, new_snapshot.data)
    elif wt == "page_content":
        changes = _diff_page_content(old_snapshot.data, new_snapshot.data)
    elif wt == "port_scan":
        changes = _diff_port_scan(old_snapshot.data, new_snapshot.data)
    else:
        changes = []

    changed = len(changes) > 0
    overall = _max_severity(changes) if changed else "info"

    if changed:
        summary = f"{len(changes)} change(s) detected (max severity: {overall})"
    else:
        summary = "No changes detected."

    return DiffResult(
        watch_id=new_snapshot.watch_id,
        target=new_snapshot.target,
        watch_type=new_snapshot.watch_type,
        old_snapshot_id=old_snapshot.id,
        new_snapshot_id=new_snapshot.id,
        changed=changed,
        changes=changes,
        summary=summary,
        detected_at=now,
    )


def _diff_http_headers(old_data: dict, new_data: dict) -> list[dict]:
    """Compare two HTTP header snapshots.

    Expects ``old_data`` / ``new_data`` to have a ``headers`` key containing
    a dict of ``{lowercase-header: value}``.
    """
    old_headers: dict[str, str] = {k.lower(): v for k, v in (old_data.get("headers") or {}).items()}
    new_headers: dict[str, str] = {k.lower(): v for k, v in (new_data.get("headers") or {}).items()}
    changes: list[dict] = []

    all_keys = set(old_headers) | set(new_headers)
    for key in sorted(all_keys):
        old_val = old_headers.get(key)
        new_val = new_headers.get(key)

        if old_val is None and new_val is not None:
            # New header added
            sev = "high" if key in SECURITY_HEADERS else "low"
            changes.append({"field": f"header:{key}", "old_value": None, "new_value": new_val, "severity": sev})
        elif old_val is not None and new_val is None:
            # Header removed
            sev = "high" if key in SECURITY_HEADERS else "low"
            changes.append({"field": f"header:{key}", "old_value": old_val, "new_value": None, "severity": sev})
        elif old_val != new_val:
            # Header value changed
            changes.append({"field": f"header:{key}", "old_value": old_val, "new_value": new_val, "severity": "low"})

    return changes


def _diff_certificate(old_data: dict, new_data: dict) -> list[dict]:
    """Compare two certificate snapshots.

    Looks at ``issuer``, ``subject``, ``not_after``, ``not_before``, ``san``,
    and ``serial_number``.
    """
    fields = ("issuer", "subject", "not_after", "not_before", "serial_number")
    changes: list[dict] = []

    for f in fields:
        old_val = old_data.get(f)
        new_val = new_data.get(f)
        if old_val != new_val and (old_val is not None or new_val is not None):
            changes.append({
                "field": f"cert:{f}",
                "old_value": old_val,
                "new_value": new_val,
                "severity": "high" if f in ("issuer", "serial_number") else "medium",
            })

    # SAN comparison (lists)
    old_san = sorted(old_data.get("san", []) or [])
    new_san = sorted(new_data.get("san", []) or [])
    if old_san != new_san:
        added = set(new_san) - set(old_san)
        removed = set(old_san) - set(new_san)
        changes.append({
            "field": "cert:san",
            "old_value": old_san,
            "new_value": new_san,
            "severity": "high",
            "detail": {"added": list(added), "removed": list(removed)},
        })

    return changes


def _diff_dns(old_data: dict, new_data: dict) -> list[dict]:
    """Compare two DNS record snapshots.

    Expects ``records`` key with ``{record_type: [values]}``.
    """
    old_records: dict[str, list[str]] = old_data.get("records") or {}
    new_records: dict[str, list[str]] = new_data.get("records") or {}
    changes: list[dict] = []

    all_types = set(old_records) | set(new_records)
    for rtype in sorted(all_types):
        old_vals = sorted(old_records.get(rtype, []) or [])
        new_vals = sorted(new_records.get(rtype, []) or [])
        if old_vals != new_vals:
            added = set(new_vals) - set(old_vals)
            removed = set(old_vals) - set(new_vals)
            changes.append({
                "field": f"dns:{rtype}",
                "old_value": old_vals,
                "new_value": new_vals,
                "severity": "medium",
                "detail": {"added": list(added), "removed": list(removed)},
            })

    return changes


def _diff_tech_stack(old_data: dict, new_data: dict) -> list[dict]:
    """Compare two technology-stack snapshots.

    Expects ``technologies`` key with a list of strings.
    """
    old_techs = sorted(old_data.get("technologies", []) or [])
    new_techs = sorted(new_data.get("technologies", []) or [])
    changes: list[dict] = []

    if old_techs != new_techs:
        added = set(new_techs) - set(old_techs)
        removed = set(old_techs) - set(new_techs)
        changes.append({
            "field": "tech_stack",
            "old_value": old_techs,
            "new_value": new_techs,
            "severity": "info",
            "detail": {"added": list(added), "removed": list(removed)},
        })

    return changes


def _diff_page_content(old_data: dict, new_data: dict) -> list[dict]:
    """Compare two page-content snapshots by hash.

    Expects ``content_hash`` or ``body_length`` keys.
    """
    changes: list[dict] = []
    old_hash = old_data.get("content_hash", "")
    new_hash = new_data.get("content_hash", "")

    if old_hash and new_hash and old_hash != new_hash:
        changes.append({
            "field": "content_hash",
            "old_value": old_hash,
            "new_value": new_hash,
            "severity": "info",
        })

    old_len = old_data.get("body_length", 0)
    new_len = new_data.get("body_length", 0)
    if old_len != new_len:
        changes.append({
            "field": "body_length",
            "old_value": old_len,
            "new_value": new_len,
            "severity": "info",
        })

    return changes


def _diff_port_scan(old_data: dict, new_data: dict) -> list[dict]:
    """Compare two port-scan snapshots.

    Expects ``open_ports`` key with a list of port numbers.
    """
    old_ports = set(old_data.get("open_ports", []) or [])
    new_ports = set(new_data.get("open_ports", []) or [])
    changes: list[dict] = []

    added = new_ports - old_ports
    removed = old_ports - new_ports

    for port in sorted(added):
        changes.append({
            "field": f"port:{port}",
            "old_value": None,
            "new_value": port,
            "severity": "medium",
        })

    for port in sorted(removed):
        changes.append({
            "field": f"port:{port}",
            "old_value": port,
            "new_value": None,
            "severity": "low",
        })

    return changes


