def collect_http_headers(target: str) -> dict:
    """Fetch HTTP response headers from *target*.

    Uses ``urllib.request`` with a 10-second timeout.  On failure, returns
    synthetic data so the pipeline can continue for demo/testing purposes.
    """
    import urllib.request as _req
    import urllib.error as _err

    url = target if target.startswith("http") else f"https://{target}"
    try:
        req = _req.Request(url, method="HEAD", headers={"User-Agent": "MIRV-Intel/1.0"})
        with _req.urlopen(req, timeout=COLLECT_TIMEOUT) as resp:
            headers = dict(resp.headers)
            # Normalise to lowercase keys
            headers = {k.lower(): v for k, v in headers.items()}
            return {
                "status_code": resp.status,
                "headers": headers,
                "collected_at": _now_iso(),
            }
    except Exception as exc:
        _logger.warning("collect_http_headers failed for %s: %s", url, exc)
        return {
            "status_code": 0,
            "headers": {},
            "collected_at": _now_iso(),
            "error": str(exc),
        }


def collect_certificate(target: str) -> dict:
    """Fetch TLS certificate information for *target*.

    Uses ``ssl`` stdlib.  On failure, returns synthetic data.
    """
    hostname = target.replace("https://", "").replace("http://", "").split(":")[0].split("/")[0]
    port = 443

    try:
        ctx = ssl.create_default_context()
        with ctx.wrap_socket(socket.socket(), server_hostname=hostname) as s:
            s.settimeout(COLLECT_TIMEOUT)
            s.connect((hostname, port))
            cert = s.getpeercert()

        # Parse cert fields
        issuer = dict(x[0] for x in cert.get("issuer", []))
        subject = dict(x[0] for x in cert.get("subject", []))
        san_list: list[str] = []
        for ext_type, ext_val in cert.get("subjectAltName", []):
            if ext_type == "DNS":
                san_list.append(ext_val)

        return {
            "issuer": issuer.get("organizationName", issuer.get("commonName", "")),
            "subject": subject.get("commonName", ""),
            "not_before": cert.get("notBefore", ""),
            "not_after": cert.get("notAfter", ""),
            "serial_number": cert.get("serialNumber", ""),
            "san": san_list,
            "collected_at": _now_iso(),
        }
    except Exception as exc:
        _logger.warning("collect_certificate failed for %s:%s: %s", hostname, port, exc)
        return {
            "issuer": "",
            "subject": hostname,
            "not_before": "",
            "not_after": "",
            "serial_number": "",
            "san": [],
            "collected_at": _now_iso(),
            "error": str(exc),
        }


def collect_dns(target: str) -> dict:
    """Resolve DNS records for *target* using ``socket.getaddrinfo``.

    Returns A and AAAA records.  On failure, returns synthetic data.
    """
    hostname = target.replace("https://", "").replace("http://", "").split(":")[0].split("/")[0]
    records: dict[str, list[str]] = {}

    try:
        addr_infos = socket.getaddrinfo(hostname, None)
        for info in addr_infos:
            fam = info[0]
            sockaddr = info[4]
            if fam == socket.AF_INET:
                ip = sockaddr[0]
                records.setdefault("A", [])
                if ip not in records["A"]:
                    records["A"].append(ip)
            elif fam == socket.AF_INET6:
                ip = sockaddr[0]
                records.setdefault("AAAA", [])
                if ip not in records["AAAA"]:
                    records["AAAA"].append(ip)

        return {
            "hostname": hostname,
            "records": records,
            "collected_at": _now_iso(),
        }
    except Exception as exc:
        _logger.warning("collect_dns failed for %s: %s", hostname, exc)
        return {
            "hostname": hostname,
            "records": {},
            "collected_at": _now_iso(),
            "error": str(exc),
        }


def collect_tech_stack(target: str) -> dict:
    """Detect technologies from HTTP headers and meta tags.

    Uses ``urllib.request`` with a 10-second timeout.  On failure, returns
    synthetic data.
    """
    import urllib.request as _req

    url = target if target.startswith("http") else f"https://{target}"
    try:
        req = _req.Request(url, headers={"User-Agent": "MIRV-Intel/1.0"})
        with _req.urlopen(req, timeout=COLLECT_TIMEOUT) as resp:
            headers = {k.lower(): v for k, v in resp.headers.items()}
            body = resp.read(65536).decode("utf-8", errors="replace")
            status = resp.status

        technologies: list[str] = []

        # Header-based detection
        server = headers.get("server", "")
        if server:
            technologies.append(f"Server:{server}")

        powered_by = headers.get("x-powered-by", "")
        if powered_by:
            technologies.append(f"X-Powered-By:{powered_by}")

        if "x-drupal-cache" in headers:
            technologies.append("Drupal")
        if "x-generator" in headers:
            technologies.append(f"Generator:{headers['x-generator']}")
        if "cf-ray" in headers:
            technologies.append("Cloudflare")
        if "x-amz-cf-id" in headers:
            technologies.append("AWS CloudFront")
        if "x-varnish" in headers:
            technologies.append("Varnish")
        if "x-akamai-transformed" in headers:
            technologies.append("Akamai")

        # Body-based detection (lightweight)
        lower_body = body.lower()
        if "wp-content" in lower_body or "wp-includes" in lower_body:
            technologies.append("WordPress")
        if "joomla" in lower_body:
            technologies.append("Joomla")
        if "drupal" in lower_body:
            technologies.append("Drupal")
        if "shopify" in lower_body:
            technologies.append("Shopify")
        if "react" in lower_body or "_reactroot" in lower_body:
            technologies.append("React")
        if "vue" in lower_body or "v-cloak" in lower_body:
            technologies.append("Vue.js")
        if "angular" in lower_body:
            technologies.append("Angular")

        return {
            "technologies": sorted(set(technologies)),
            "status_code": status,
            "collected_at": _now_iso(),
        }
    except Exception as exc:
        _logger.warning("collect_tech_stack failed for %s: %s", url, exc)
        return {
            "technologies": [],
            "status_code": 0,
            "collected_at": _now_iso(),
            "error": str(exc),
        }


