def create_alert(
    watch_id: str,
    target: str,
    alert_type: str,
    severity: str,
    message: str,
    details: Optional[dict] = None,
) -> IntelAlert:
    """Create an alert and store it.  Returns the new ``IntelAlert``."""
    with _lock:
        if len(_alerts) >= MAX_ALERTS:
            # Evict oldest acknowledged alerts first, then any
            acked = [a for a in _alerts.values() if a.acknowledged]
            if acked:
                oldest = min(acked, key=lambda a: a.created_at)
                _alerts.pop(oldest.id, None)
            else:
                oldest = min(_alerts.values(), key=lambda a: a.created_at)
                _alerts.pop(oldest.id, None)

        alert = IntelAlert(
            id=str(uuid.uuid4()),
            watch_id=watch_id,
            target=target,
            alert_type=alert_type,
            severity=severity,
            message=message,
            details=details or {},
            created_at=_now_iso(),
            acknowledged=False,
        )
        _alerts[alert.id] = alert
        _logger.info("Alert created: %s [%s] %s", alert.id, severity, alert_type)
        return alert


def list_alerts(
    watch_id: Optional[str] = None,
    severity: Optional[str] = None,
    limit: int = 100,
) -> list[IntelAlert]:
    """Return alerts, optionally filtered by *watch_id* and/or *severity*."""
    with _lock:
        alerts = list(_alerts.values())

    if watch_id is not None:
        alerts = [a for a in alerts if a.watch_id == watch_id]
    if severity is not None:
        alerts = [a for a in alerts if a.severity == severity]

    # Most recent first
    alerts.sort(key=lambda a: a.created_at, reverse=True)
    return alerts[:limit]


def acknowledge_alert(alert_id: str) -> bool:
    """Acknowledge an alert by ID.  Returns True on success."""
    with _lock:
        alert = _alerts.get(alert_id)
        if alert is None:
            return False
        alert.acknowledged = True
        _logger.info("Alert acknowledged: %s", alert_id)
        return True


def clear_alerts(watch_id: Optional[str] = None) -> int:
    """Delete alerts, optionally only for a specific watch.  Returns count."""
    with _lock:
        if watch_id is None:
            count = len(_alerts)
            _alerts.clear()
        else:
            to_remove = [aid for aid, a in _alerts.items() if a.watch_id == watch_id]
            for aid in to_remove:
                _alerts.pop(aid, None)
            count = len(to_remove)
    _logger.info("Cleared %d alert(s)", count)
    return count


